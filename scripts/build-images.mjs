import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { cars } from '../data/cars.js';
import { drivers } from '../data/drivers.js';
import { gallery } from '../data/archive.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputRoot = path.join(root, 'assets', 'optimized');

const sources = new Set(['assets/hero-vistula-lemans.jpg']);
cars.forEach((car) => {
  sources.add(car.image);
  sources.add(car.heroImage);
  if (car.showroomImage) sources.add(car.showroomImage);
  car.gallery.forEach((image) => sources.add(image));
  car.liveries.forEach((livery) => sources.add(livery.image));
});
drivers.forEach((driver) => {
  if (driver.photo) sources.add(driver.photo);
  if (driver.showcaseImage) sources.add(driver.showcaseImage);
});
gallery.forEach((item) => {
  sources.add(item.thumbnail);
  sources.add(item.image);
});

const outputBase = (source) => {
  const parsed = path.parse(source);
  const relativeDir = source.startsWith('assets/') ? parsed.dir.replace(/^assets[\\/]/, '') : path.join('root', parsed.dir);
  return path.join(outputRoot, relativeDir, parsed.name);
};

const selectWidths = (source, sourceWidth) => {
  let candidates = [800, 1280, 1920];
  if (source.includes('/thumbs/') || source.includes('/drivers/') || source.includes('/avatar_')) candidates = [480, 800];
  if (source.includes('/cars/') && !source.includes('/thumbs/')) candidates = [800, 1280];
  if (source.includes('/liveries/')) candidates = [800];
  return candidates.filter((width) => width <= sourceWidth);
};

const manifest = {};
let generated = 0;

for (const source of [...sources].sort()) {
  const input = path.join(root, source);
  const metadata = await sharp(input).metadata();
  const widths = selectWidths(source.replace(/\\/g, '/'), metadata.width);
  const base = outputBase(source);
  await fs.mkdir(path.dirname(base), { recursive: true });
  manifest[source.replace(/\\/g, '/')] = { width: metadata.width, height: metadata.height, avif: [], webp: [] };

  for (const width of widths) {
    for (const format of ['avif', 'webp']) {
      const filePath = `${base}-${width}.${format}`;
      const pipeline = sharp(input).resize({ width, withoutEnlargement: true });
      if (format === 'avif') await pipeline.avif({ quality: 48, effort: 5 }).toFile(filePath);
      else await pipeline.webp({ quality: 76, effort: 5 }).toFile(filePath);
      const relative = path.relative(root, filePath).replace(/\\/g, '/');
      manifest[source.replace(/\\/g, '/')][format].push({ src: relative, width });
      generated += 1;
    }
  }
}

const manifestSource = `// Generated by scripts/build-images.mjs. Do not edit manually.\nexport const imageManifest = ${JSON.stringify(manifest, null, 2)};\n`;
await fs.writeFile(path.join(root, 'data', 'image-manifest.js'), manifestSource, 'utf8');
console.log(`Generated ${generated} optimized image variants for ${sources.size} source files.`);
